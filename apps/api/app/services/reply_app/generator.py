"""Generate a self-contained HTML mini-app with Grok."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any, Optional

from app.config import get_settings
from app.services import xai_client
from app.services.reply_app.intent import AppIntent


@dataclass
class GeneratedApp:
    title: str
    summary: str
    html: str
    model: str
    metadata: dict[str, Any]


_HTML_FENCE = re.compile(r"```(?:html)?\s*([\s\S]*?)```", re.I)


def _extract_html(content: str) -> str:
    content = (content or "").strip()
    m = _HTML_FENCE.search(content)
    if m:
        return m.group(1).strip()
    # bare document
    if "<html" in content.lower() or content.lstrip().startswith("<!DOCTYPE"):
        # strip leading junk before doctype/html
        lower = content.lower()
        idx = lower.find("<!doctype")
        if idx < 0:
            idx = lower.find("<html")
        if idx >= 0:
            return content[idx:].strip()
    return content


def _sanitize_html(html: str) -> str:
    """Light safety pass — not a full XSS auditor, just block obvious footguns."""
    # Remove script src= external (keep inline)
    html = re.sub(
        r"<script[^>]+src\s*=\s*[\"']https?://[^\"']+[\"'][^>]*>\s*</script>",
        "<!-- external script stripped -->",
        html,
        flags=re.I,
    )
    # Block javascript: URLs in href
    html = re.sub(r"""href\s*=\s*["']\s*javascript:""", 'href="#blocked"', html, flags=re.I)
    return html


