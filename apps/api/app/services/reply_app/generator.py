async def generate_html_app(intent: AppIntent) -> GeneratedApp:
    settings = get_settings()
    model = settings.xai_model
    system = (
        "You build tiny, beautiful, self-contained web apps as a SINGLE HTML document. "
        "Requirements:\n"
        "1. Return ONLY HTML (optional ```html fence). Start with <!DOCTYPE html>.\n"
        "2. Inline all CSS and JS. No build tools. Prefer zero external scripts.\n"
        "3. Mobile-first, works in X in-app browser, dark-friendly aesthetic.\n"
        "4. Actually interactive and useful for the brief — not a static landing page.\n"
        "5. Use localStorage when it helps. No backend calls, no API keys, no tracking.\n"
        "6. Accessible labels, large tap targets, clear primary action.\n"
        "7. Footer line: 'Generated by Grok Reply App'.\n"
        "8. Do not include markdown outside the HTML."
    )
    user = (
        f"Title: {intent.title}\n"
        f"Type: {intent.app_type}\n"
        f"Brief:\n{intent.brief}\n\n"
        "Build the complete app now."
    )

    try:
        content = await xai_client.chat_text(system, user, temperature=0.4)
        html = _sanitize_html(_extract_html(content))
        if "<html" not in html.lower():
            html = _fallback_html(intent.title, intent.brief)
            meta_note = "fallback_shell"
        else:
            meta_note = "grok_html"
        # Ensure doctype
        if not html.lstrip().lower().startswith("<!doctype"):
            html = "<!DOCTYPE html>\n" + html
    except Exception as e:
        html = _fallback_html(intent.title, intent.brief)
        meta_note = f"fallback_error:{e}"

    return GeneratedApp(
        title=intent.title,
        summary=intent.brief[:240],
        html=html,
        model=model,
        metadata={"generator": meta_note, "app_type": intent.app_type},
    )


async def maybe_preview_image(title: str, brief: str) -> Optional[bytes]:
    """Optional Imagine preview; returns PNG bytes or None."""
    settings = get_settings()
    if not settings.reply_app_attach_preview_image or not settings.xai_configured:
        return None
    prompt = (
        f"Clean mobile UI screenshot mockup of a minimal dark-mode web app titled '{title}'. "
        f"Purpose: {brief[:200]}. Flat product design, no real logos, no watermarks, "
        "centered phone frame, high contrast."
    )
    try:
        url = await xai_client.generate_image_url(prompt)
    except Exception:
        return None
    if not url:
        return None
    try:
        import httpx
        import base64

        if url.startswith("data:image"):
            # data:image/png;base64,...
            b64 = url.split(",", 1)[1]
            return base64.b64decode(b64)
        async with httpx.AsyncClient(timeout=60.0) as client:
            r = await client.get(url)
            r.raise_for_status()
            return r.content
    except Exception:
        return None
